function telemetry(ctx, config, order, fmtVal, getMetricStatus) {
  return order.map((key) => {
    const metric = config.metrics[key];
    const [label, unit] = METRICS[key];
    return '- ' + label + ': **' + fmtVal(ctx.values[key], metric) + ' ' + unit + '** [' + STATUS[getMetricStatus(metric, ctx.values[key])] + ']';
  }).join('\n');
}

export function buildArabicResponse(question, ctx, { config, order, fmtVal, getMetricStatus, getOverallStatus, prediction }) {
  const scenario = SCENARIOS[ctx.scenarioId] || SCENARIOS.nominal;
  const status = getOverallStatus(ctx.values);
  const lower = String(question || '').toLowerCase();
  const pending = scenario.steps.map((text, i) => ({ n: i + 1, text })).filter((step) => !ctx.checkedSteps.includes(step.n - 1));
  const readout = telemetry(ctx, config, order, fmtVal, getMetricStatus);
  if (['report', 'downlink', 'earth', 'تقرير', 'تقارير', 'الأرض', 'الارض', 'إرسال', 'ارسال'].some((word) => lower.includes(word))) {
    return '### تقرير طبي للإرسال إلى الأرض — ZeroG Pulse\n'
      + '**معرّف التقرير:** ZGP-DL-' + Date.now() + ' · **المهمة:** ' + config.downlink.missionId + '\n'
      + '**زمن المهمة (MET):** ' + ctx.met + ' · **المركبة:** ' + config.mission.craft + ' · **تأخر الاتصال باتجاه واحد:** ' + config.comm.label + '\n'
      + '**فرد الطاقم:** ' + ctx.crew.callsign + ' ' + ctx.crew.name + ' (' + (ROLES[ctx.crew.role] || ctx.crew.role) + ')\n'
      + '**السيناريو النشط:** ' + scenario.title + ' · **الحالة العامة:** ' + STATUS[status] + '\n\n'
      + '**القياسات الفسيولوجية والبيئية**\n' + readout + '\n\n'
      + '**الإجراءات المضادة الموصى بها**\n' + scenario.steps.map((step, i) => (i + 1) + '. ' + step).join('\n')
      + '\n\n---\nأُرسل ذاتياً بواسطة MED-AI · الزمن المتوقع لرد مركز التحكم الأرضي نحو 29 دقيقة (زمن الضوء ذهاباً وإياباً).';
  }
  let out = '### التقييم السريري — ' + ctx.crew.callsign + ' ' + ctx.crew.name + '\n'
    + '**الحالة النشطة:** ' + scenario.title + ' (' + STATUS[ctx.scenario.severity] + ') · **الحالة العامة: ' + STATUS[status] + '**\n\n'
    + '**القياسات المباشرة** (متحقق منها عند ' + ctx.met + ' MET):\n' + readout + '\n\n'
    + '**التوقع خلال 30 دقيقة:** خطر بنسبة ' + prediction.risk + '% — ' + scenario.condition
    + (prediction.minutes ? ' · الزمن التقريبي لبلوغ العتبة: ' + prediction.minutes + ' دقيقة' : '')
    + ' · أُنجز ' + ctx.checkedSteps.length + '/' + scenario.steps.length + ' من الإجراءات المضادة\n';
  if (['okay', 'ok', 'safe', 'survive', 'prognos', 'مستقر', 'آمن', 'امن', 'بخير', 'ينجو', 'توقع', 'خطير'].some((word) => lower.includes(word))) {
    out += '\n**المآل السريري:** ' + (status === 'CRITICAL'
      ? 'فرد الطاقم غير مستقر. دون التنفيذ الفوري للإجراءات المتبقية يُتوقع التدهور خلال نحو ' + prediction.minutes + ' دقيقة. مع الالتزام الكامل بالقائمة يُتوقع التعافي خلال هذه الدورة.'
      : status === 'WARNING'
        ? 'الحالة متماسكة سريرياً لكنها متراجعة؛ الاحتياطي العصبي الذاتي دون هامش الراحة لقواعد الرحلة. تعيد الإجراءات التالية هامش الأمان خلال هذه الدورة.'
        : 'الحالة مستقرة سريرياً؛ جميع المعايير ضمن حدود قواعد الرحلة في NASA-STD-3001.') + '\n';
  }
  const topic = KNOWLEDGE.find((entry) => entry.keywords.some((word) => lower.includes(word)));
  const why = ['why', 'explain', 'cause', 'mechanism', 'لماذا', 'ليش', 'لم', 'سبب', 'اشرح', 'فسر', 'فسّر', 'كيف'].some((word) => lower.includes(word));
  if (why || topic) {
    out += '\n**' + (why ? 'الآلية المرضية' : 'الإحاطة السريرية') + ':** ' + (topic?.reply || scenario.alert) + '\n';
  }
  out += '\n**خطة العمل العاجلة — نفّذ بالترتيب:**\n';
  if (!pending.length) {
    out += '- اكتملت الإجراءات المضادة وعددها ' + scenario.steps.length + '. واصل المراقبة وأعد فحص العلامات الحيوية بعد 10 دقائق.\n';
  } else {
    out += pending.slice(0, 4).map((step) => step.n + '. ' + step.text).join('\n')
      + '\n\nتبقّى ' + pending.length + ' من الإجراءات؛ إكمالها يخفض درجة الخطر البالغة ' + prediction.risk + '%.';
  }
  return out + '\n\n---\nالمعايير: **NASA-STD-3001 / OSD-51 / OSD-194** · MED-AI يعمل ذاتياً (الأرض على بُعد ' + config.comm.label + ' زمنياً باتجاه واحد).';
}
